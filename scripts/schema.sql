PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS posts (
 id INTEGER PRIMARY KEY, title TEXT NOT NULL, slug TEXT NOT NULL UNIQUE, content TEXT NOT NULL,
 excerpt TEXT NOT NULL DEFAULT '', created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL,
 status TEXT NOT NULL DEFAULT 'draft', type TEXT NOT NULL DEFAULT 'post', category TEXT NOT NULL DEFAULT '',
 tags TEXT NOT NULL DEFAULT '[]', cover TEXT NOT NULL DEFAULT '', views INTEGER NOT NULL DEFAULT 0,
 allow_comment INTEGER NOT NULL DEFAULT 1, pinned INTEGER NOT NULL DEFAULT 0, format TEXT NOT NULL DEFAULT 'markdown',
 legacy_content TEXT, legacy_fields TEXT NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS posts_public ON posts(status,type,created_at DESC);
CREATE TABLE IF NOT EXISTS comments (
 id INTEGER PRIMARY KEY, post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
 parent_id INTEGER NOT NULL DEFAULT 0, author TEXT NOT NULL, email TEXT NOT NULL DEFAULT '', url TEXT NOT NULL DEFAULT '',
 content TEXT NOT NULL, created_at INTEGER NOT NULL, status TEXT NOT NULL DEFAULT 'waiting'
);
CREATE INDEX IF NOT EXISTS comments_post ON comments(post_id,status,created_at);
CREATE TABLE IF NOT EXISTS taxonomies (id INTEGER PRIMARY KEY, name TEXT NOT NULL, slug TEXT NOT NULL, type TEXT NOT NULL, description TEXT NOT NULL DEFAULT '', UNIQUE(slug,type));
CREATE TABLE IF NOT EXISTS post_taxonomies (post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE, taxonomy_id INTEGER NOT NULL REFERENCES taxonomies(id) ON DELETE CASCADE, PRIMARY KEY(post_id,taxonomy_id));
CREATE TABLE IF NOT EXISTS settings (id INTEGER PRIMARY KEY CHECK(id=1), value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS admins (id INTEGER PRIMARY KEY CHECK(id=1), username TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL, created_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (id TEXT PRIMARY KEY, admin_id INTEGER NOT NULL REFERENCES admins(id) ON DELETE CASCADE, expires_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS auth_meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS rate_limits (key TEXT PRIMARY KEY, count INTEGER NOT NULL, expires_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS media (id INTEGER PRIMARY KEY, name TEXT NOT NULL, url TEXT NOT NULL UNIQUE, mime TEXT NOT NULL, size INTEGER NOT NULL, created_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS legacy_records (table_name TEXT NOT NULL, row_id INTEGER NOT NULL, value TEXT NOT NULL, PRIMARY KEY(table_name,row_id));
CREATE TABLE IF NOT EXISTS integration_secrets (provider TEXT PRIMARY KEY, secret TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS integration_locks (provider TEXT PRIMARY KEY, owner TEXT NOT NULL, expires_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS integration_schedules (provider TEXT PRIMARY KEY, next_run_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS bangumi_state (
 id INTEGER PRIMARY KEY CHECK(id=1), account_json TEXT, items_json TEXT NOT NULL DEFAULT '[]',
 synced_at TEXT, last_error TEXT
);
